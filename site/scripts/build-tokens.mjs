// Compiles design-system/tokens.json into src/styles/tokens.css and copies the
// font files into public/fonts/.
//
// tokens.json is the single source of truth for the Provisa design system. The
// same file is published to the Design System artifact, which compiles it with
// the same rules used here: every color, spacing, radius and other token becomes
// a `--<name>` custom property, each font family a `--font-<key>` property, each
// type style a `.<name>` class, and each font file an @font-face rule. Keeping
// the two compilers in step is what lets src/styles/ds.css ship unchanged as the
// artifact's bundle.css.
import { copyFile, mkdir, readFile, readdir, writeFile } from 'node:fs/promises';
import { basename, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const tokensPath = join(root, 'design-system', 'tokens.json');
const outCss = join(root, 'src', 'styles', 'tokens.css');
const fontsSrc = join(root, 'design-system', 'fonts');
const fontsOut = join(root, 'public', 'fonts');

const tokens = JSON.parse(await readFile(tokensPath, 'utf8'));

// Families whose entries are plain `{name, value}` lists. `color` and `type`
// are handled separately; `meta` is provenance, not tokens.
const SKIP = new Set(['name', 'version', 'color', 'type', 'meta']);

const colorValue = (value) => {
  const alias = /^\{([A-Za-z0-9][A-Za-z0-9_.-]*)\}$/.exec(value);
  return alias ? `var(--${alias[1]})` : value.toLowerCase();
};

const lines = [
  '/* GENERATED by scripts/build-tokens.mjs from design-system/tokens.json. Do not edit. */',
  '',
];

// Colors: one theme today; the first theme is also :root, as in the artifact.
const themes = tokens.color.themes;
const first = themes[0].id;
lines.push(`:root, [data-theme="${first}"] {`);
for (const t of tokens.color.tokens) {
  const v = typeof t.value === 'string' ? t.value : t.value[first];
  lines.push(`  --${t.name}: ${colorValue(v)};`);
}
lines.push('}');
for (const theme of themes.slice(1)) {
  lines.push(`[data-theme="${theme.id}"] {`);
  for (const t of tokens.color.tokens) {
    if (typeof t.value === 'object' && t.value[theme.id]) {
      lines.push(`  --${t.name}: ${colorValue(t.value[theme.id])};`);
    }
  }
  lines.push('}');
}
lines.push('');

// Every other token family, then the font family stacks.
lines.push(':root {');
for (const [family, group] of Object.entries(tokens)) {
  if (SKIP.has(family) || !group?.tokens) continue;
  for (const t of group.tokens) lines.push(`  --${t.name}: ${t.value};`);
}
for (const [key, stack] of Object.entries(tokens.type.families)) {
  lines.push(`  --font-${key}: ${stack};`);
}
lines.push('}');
lines.push('');

// Type styles become classes named after the style.
const length = (v) => (typeof v === 'number' ? `${v}px` : v);
for (const group of tokens.type.groups) {
  for (const s of group.styles) {
    const family = s.family ?? group.family;
    const decl = [`font-family: var(--font-${family})`, `font-size: ${length(s.fontSize)}`];
    if (s.lineHeight !== undefined) decl.push(`line-height: ${s.lineHeight}`);
    if (s.fontWeight !== undefined) decl.push(`font-weight: ${s.fontWeight}`);
    if (s.fontStyle !== undefined) decl.push(`font-style: ${s.fontStyle}`);
    if (s.letterSpacing !== undefined) decl.push(`letter-spacing: ${length(s.letterSpacing)}`);
    lines.push(`.${s.name} { ${decl.join('; ')}; }`);
  }
}
lines.push('');

// Font files. The site serves them from /fonts/.
for (const f of tokens.type.fonts) {
  lines.push(
    `@font-face { font-family: "${f.family}"; src: url("/fonts/${basename(f.file)}") format("woff2"); ` +
      `font-weight: ${f.weight}; font-style: ${f.style ?? 'normal'}; font-display: swap; }`,
  );
}
lines.push('');

await mkdir(dirname(outCss), { recursive: true });
await writeFile(outCss, lines.join('\n'));

await mkdir(fontsOut, { recursive: true });
for (const file of await readdir(fontsSrc)) {
  if (file.endsWith('.woff2')) await copyFile(join(fontsSrc, file), join(fontsOut, file));
}

console.log(`tokens: wrote ${outCss.replace(root + '/', '')} and copied fonts to public/fonts/`);
